"""Task 15 Part C.2: regenerate the thesis figures B.1 and B.3-B.12 with no result or figure numbers in any text element.
The plotting scripts are copied with text-element edits only (listed in TEXT_EDITS) and an output redirect, written to t15/gen/,
and run through fig_harness (which records each figure's arrays and texts for checks C5 and C7). Data, parameters and curves are
untouched. Outputs: figs_thesis/B.n_<key>.png (and .pdf where the script writes PDF). B.2 comes from make_fig_B2.py.
Usage: python3 make_figs_thesis.py"""
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
CLS = os.path.dirname(HERE)
GEN = os.path.join(HERE, "gen")
OUTDIR = os.path.join(CLS, "figs_thesis")
sys.path.insert(0, HERE)
import fig_harness  # noqa: E402

# (old text, new text): text elements carrying result numbers; nothing else changes
TEXT_EDITS = [('ax2.set_title("class in each band (Theorem 2)", pad=8)', 'ax2.set_title("class in each band", pad=8)'),
              ('label="realized curve with three windows (Corollary 48)")', 'label="realized curve with three windows")'),
              ('label="the single maximum (Theorem 25)")', 'label="the single maximum")')]


def names():
    F = yaml.safe_load(open(os.path.join(CLS, "register", "figures.yaml")))
    return {os.path.basename(e["source_file"]): f"{e['label']}_{e['key']}" for e in F if e["source_file"]}


def gen_t13(nm):
    s = open(os.path.join(CLS, "t13", "t13_figures_paper2.py")).read()
    for a, b in TEXT_EDITS:
        assert s.count(a) == 1, a
        s = s.replace(a, b)
    a = 'OUT = os.path.join(CLS, "figs_paper2")'
    assert s.count(a) == 1
    s = s.replace(a, 'OUT = os.environ["FIG_OUT"]\nNAMES = ' + repr(nm))
    a = '''    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(OUT, f"{nm}.{ext}"), dpi=300)
    plt.close(fig)
    with open(os.path.join(OUT, f"{nm}.txt"), "w") as fh:
        fh.write(cap.strip() + "\\n")
    CAPS[nm] = cap'''
    assert s.count(a) == 1
    s = s.replace(a, '''    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(OUT, f"{NAMES[nm]}.{ext}"), dpi=300)
    plt.close(fig)
    CAPS[nm] = cap   # captions are rendered from source/figs/ (register), not written here''')
    i = s.index('\nwith open(os.path.join(OUT, "README.md"), "w") as fh:')
    j = s.index('print("figures:", len(CAPS))')
    s = s[:i] + "\n" + s[j:]
    s = s.replace('"""Part E: the Paper 2 figure set', '"""GENERATED by t15/make_figs_thesis.py from t13/t13_figures_paper2.py (text edits '
                  'and output redirect only).\nPart E: the Paper 2 figure set', 1)
    s = s.replace("from t13_common import CLS", "sys.path.insert(0, os.path.join(os.environ['CLS_DIR'], 't13'))\nfrom t13_common import CLS")
    return s


def gen_t8(nm):
    s = open(os.path.join(CLS, "t8_figures.py")).read()
    a = 'p = os.path.join(FIG, "fig_t8_sweeps.png")'
    assert s.count(a) == 1
    s = s.replace(a, 'p = os.path.join(os.environ["FIG_OUT"], ' + repr(nm["fig_t8_sweeps"] + ".png") + ")")
    s = s.replace('"""T8.6:', '"""GENERATED by t15/make_figs_thesis.py from t8_figures.py (output redirect only).\nT8.6:', 1)
    s = s.replace("from t8_common import", "import sys\nsys.path.insert(0, os.environ['CLS_DIR'])\nfrom t8_common import", 1)
    return s


def main():
    nm = names()
    os.makedirs(GEN, exist_ok=True)
    os.makedirs(OUTDIR, exist_ok=True)
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    os.environ["FIG_OUT"], os.environ["CLS_DIR"] = OUTDIR, CLS
    for fn, src in (("gen_figs_t13.py", gen_t13(nm)), ("gen_figs_t8.py", gen_t8(nm))):
        open(os.path.join(GEN, fn), "w").write(src)
    fig_harness.capture(os.path.join(GEN, "gen_figs_t13.py"), os.path.join(HERE, "results", "cap_new_t13.pkl"),
                        cwd=os.path.join(CLS, "t13"))
    fig_harness.capture(os.path.join(GEN, "gen_figs_t8.py"), os.path.join(HERE, "results", "cap_new_t8.pkl"), cwd=CLS)
    import make_fig_B2
    make_fig_B2.main(capture=True)
    print("written:", sorted(f for f in os.listdir(OUTDIR) if f.startswith("B.")))


if __name__ == "__main__":
    main()
